function keyFor(id) {
  return `${KEY_PREFIX}${id}.mp4`;
}

function idFrom(key) {
  const match = key.match(new RegExp(`^${KEY_PREFIX}(${ID_PATTERN})\\.mp4$`));
  return match ? match[1] : null;
}

function describe(object, origin) {
  const id = idFrom(object.key);
  const meta = object.customMetadata || {};
  const uploaded = object.uploaded instanceof Date ? object.uploaded : new Date(object.uploaded);
  return {
    id,
    title: meta.title || "Untitled",
    size: object.size,
    uploaded: uploaded.toISOString(),
    expires: new Date(uploaded.getTime() + TTL_MS).toISOString(),
    url: `${origin}/v/${id}`,
  };
}

/** 128 random bits as 26 lowercase base32 characters: URL-safe, case-insensitive, unguessable. */
function newID() {
  const bytes = crypto.getRandomValues(new Uint8Array(16));
  let bits = 0;
  let value = 0;
  let out = "";
  for (const byte of bytes) {
    value = ((value << 8) | byte) >>> 0;
    bits += 8;
    while (bits >= 5) {
      out += BASE32[(value >>> (bits - 5)) & 31];
      bits -= 5;
    }
  }
  if (bits > 0) out += BASE32[(value << (5 - bits)) & 31];
  return out;
}

function cleanTitle(value) {
  if (typeof value !== "string") return "Untitled";
  const cleaned = value.replace(/[\x00-\x1f\x7f]/g, " ").replace(/\s+/g, " ").trim().slice(0, 120);
  return cleaned || "Untitled";
}

function asciiFilename(title) {
  const cleaned = title.replace(/[^A-Za-z0-9 ._-]/g, "_").replace(/\s+/g, " ").trim();
  return cleaned || "video";
}

async function readJSON(request) {
  try {
    const value = await request.json();
    return value && typeof value === "object" && !Array.isArray(value) ? value : null;
  } catch {
    return null;
  }
}

function storageError(prefix, error) {
  const message = error && error.message ? error.message : String(error);
  // R2 reports both client mistakes (bad part size, unknown upload) and transient trouble
  // through thrown errors. 502 keeps the app retrying only for the transient kind after it has
  // given up on the request as a whole.
  const clientMistake = /part|upload|not found|does not exist|invalid/i.test(message);
  return json({ error: `${prefix}: ${message}` }, clientMistake ? 400 : 502);
}

function json(data, status = 200) {
  return new Response(JSON.stringify(data), {
    status,
    headers: { "Content-Type": "application/json; charset=utf-8", "Cache-Control": "no-store" },
  });
}
